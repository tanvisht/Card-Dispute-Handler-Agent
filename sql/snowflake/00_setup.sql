-- Run once as ACCOUNTADMIN / SYSADMIN.
CREATE ROLE IF NOT EXISTS TRIAGE_ROLE;
CREATE ROLE IF NOT EXISTS TRIAGE_BI_READER;          -- Power BI service account
CREATE WAREHOUSE IF NOT EXISTS TRIAGE_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
CREATE DATABASE IF NOT EXISTS DISPUTE_TRIAGE;
CREATE SCHEMA IF NOT EXISTS DISPUTE_TRIAGE.CORE;     -- pipeline-owned tables
CREATE SCHEMA IF NOT EXISTS DISPUTE_TRIAGE.MART;     -- BI-facing views

GRANT USAGE ON WAREHOUSE TRIAGE_WH TO ROLE TRIAGE_ROLE;
GRANT USAGE ON WAREHOUSE TRIAGE_WH TO ROLE TRIAGE_BI_READER;
GRANT USAGE ON DATABASE DISPUTE_TRIAGE TO ROLE TRIAGE_ROLE;
GRANT USAGE ON DATABASE DISPUTE_TRIAGE TO ROLE TRIAGE_BI_READER;
GRANT ALL ON SCHEMA DISPUTE_TRIAGE.CORE TO ROLE TRIAGE_ROLE;
GRANT ALL ON SCHEMA DISPUTE_TRIAGE.MART TO ROLE TRIAGE_ROLE;
GRANT USAGE ON SCHEMA DISPUTE_TRIAGE.MART TO ROLE TRIAGE_BI_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA DISPUTE_TRIAGE.MART TO ROLE TRIAGE_BI_READER;
