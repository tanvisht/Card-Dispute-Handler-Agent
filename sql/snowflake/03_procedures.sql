USE SCHEMA DISPUTE_TRIAGE.CORE;

-- Idempotent upsert from staging; safe to re-run the same batch.
CREATE OR REPLACE PROCEDURE SP_MERGE_COMPLAINTS()
RETURNS STRING LANGUAGE SQL AS
$$
BEGIN
  MERGE INTO RAW_COMPLAINTS t
  USING (SELECT * FROM STG_COMPLAINTS
         QUALIFY ROW_NUMBER() OVER (PARTITION BY COMPLAINT_ID ORDER BY DATE_RECEIVED DESC) = 1) s
  ON t.COMPLAINT_ID = s.COMPLAINT_ID
  WHEN MATCHED THEN UPDATE SET
    COMPANY_RESPONSE = s.COMPANY_RESPONSE, TIMELY = s.TIMELY, DATE_SENT_TO_COMPANY = s.DATE_SENT_TO_COMPANY
  WHEN NOT MATCHED THEN INSERT (COMPLAINT_ID, DATE_RECEIVED, PRODUCT, SUB_PRODUCT, ISSUE, SUB_ISSUE,
    NARRATIVE, COMPANY, STATE, SUBMITTED_VIA, COMPANY_RESPONSE, TIMELY, DATE_SENT_TO_COMPANY)
  VALUES (s.COMPLAINT_ID, s.DATE_RECEIVED, s.PRODUCT, s.SUB_PRODUCT, s.ISSUE, s.SUB_ISSUE,
    s.NARRATIVE, s.COMPANY, s.STATE, s.SUBMITTED_VIA, s.COMPANY_RESPONSE, s.TIMELY, s.DATE_SENT_TO_COMPANY);
  TRUNCATE TABLE STG_COMPLAINTS;
  RETURN 'ok';
END;
$$;
