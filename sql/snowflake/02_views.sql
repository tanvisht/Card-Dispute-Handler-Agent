-- BI-facing semantic layer consumed by Power BI (DirectQuery or Import).
USE SCHEMA DISPUTE_TRIAGE.MART;

CREATE OR REPLACE VIEW V_CASES AS
WITH LATEST AS (
  SELECT * FROM CORE.CLASSIFICATIONS
  QUALIFY ROW_NUMBER() OVER (PARTITION BY COMPLAINT_ID ORDER BY CLASSIFIED_AT DESC) = 1),
REV AS (
  SELECT * FROM CORE.REVIEW_DECISIONS
  QUALIFY ROW_NUMBER() OVER (PARTITION BY COMPLAINT_ID ORDER BY REVIEWED_AT DESC) = 1)
SELECT r.COMPLAINT_ID, r.DATE_RECEIVED, r.DATE_SENT_TO_COMPANY, r.COMPANY, r.STATE, r.PRODUCT,
       r.ISSUE, r.SUB_ISSUE, r.COMPANY_RESPONSE, r.TIMELY,
       COALESCE(v.ROOT_CAUSE, l.ROOT_CAUSE) AS ROOT_CAUSE,
       COALESCE(v.PRIORITY,  l.PRIORITY)    AS PRIORITY,
       l.ROOT_CAUSE AS MODEL_ROOT_CAUSE, l.PRIORITY AS MODEL_PRIORITY,
       l.VISA_REASON_CODE, l.MASTERCARD_REASON_CODE, l.REASON_CODE_LABEL,
       l.IS_FRAUD, l.CONFIDENCE, l.NEEDS_HUMAN_REVIEW, l.REVIEW_REASONS, l.CLASSIFIER, l.PROMPT_VERSION,
       v.REVIEWER, v.REVIEWED_AT,
       IFF(v.COMPLAINT_ID IS NOT NULL AND v.ROOT_CAUSE <> l.ROOT_CAUSE, TRUE, FALSE) AS MODEL_OVERRIDDEN,
       CASE WHEN v.COMPLAINT_ID IS NOT NULL THEN 'REVIEWED'
            WHEN l.NEEDS_HUMAN_REVIEW THEN 'PENDING_REVIEW'
            ELSE 'AUTO_TRIAGED' END AS CASE_STATUS,
       DATEDIFF('day', r.DATE_RECEIVED, COALESCE(v.REVIEWED_AT::DATE, CURRENT_DATE())) AS AGE_DAYS,
       CASE WHEN AGE_DAYS <= 15 THEN '0-15' WHEN AGE_DAYS <= 30 THEN '16-30'
            WHEN AGE_DAYS <= 60 THEN '31-60' ELSE '60+' END AS AGING_BUCKET,
       DATE_TRUNC('week', r.DATE_RECEIVED) AS WEEK_RECEIVED,
       DATE_TRUNC('month', r.DATE_RECEIVED) AS MONTH_RECEIVED
FROM CORE.RAW_COMPLAINTS r
JOIN LATEST l ON l.COMPLAINT_ID = r.COMPLAINT_ID
LEFT JOIN REV v ON v.COMPLAINT_ID = r.COMPLAINT_ID;

-- Category trend: monthly volume per root cause with MoM change.
CREATE OR REPLACE VIEW V_CATEGORY_TRENDS AS
SELECT MONTH_RECEIVED, ROOT_CAUSE, COUNT(*) AS CASES,
       COUNT(*) - LAG(COUNT(*)) OVER (PARTITION BY ROOT_CAUSE ORDER BY MONTH_RECEIVED) AS MOM_DELTA,
       SUM(IFF(IS_FRAUD, 1, 0)) AS FRAUD_CASES
FROM V_CASES GROUP BY 1, 2;

-- Recurring issues: company x root cause combos that repeat (>= 5 in trailing 90 days).
CREATE OR REPLACE VIEW V_RECURRING_ISSUES AS
SELECT COMPANY, ROOT_CAUSE, COUNT(*) AS CASES_90D,
       MIN(DATE_RECEIVED) AS FIRST_SEEN, MAX(DATE_RECEIVED) AS LAST_SEEN,
       SUM(IFF(PRIORITY = 'P1', 1, 0)) AS P1_CASES
FROM V_CASES
WHERE DATE_RECEIVED >= DATEADD('day', -90, CURRENT_DATE())
GROUP BY 1, 2 HAVING COUNT(*) >= 5;

-- Case aging for the review queue.
CREATE OR REPLACE VIEW V_CASE_AGING AS
SELECT AGING_BUCKET, PRIORITY, CASE_STATUS, COUNT(*) AS CASES, AVG(AGE_DAYS) AS AVG_AGE_DAYS
FROM V_CASES GROUP BY 1, 2, 3;

-- Model quality from human reviews (online accuracy).
CREATE OR REPLACE VIEW V_MODEL_QUALITY AS
SELECT DATE_TRUNC('week', REVIEWED_AT) AS WEEK, CLASSIFIER, PROMPT_VERSION, COUNT(*) AS REVIEWED,
       AVG(IFF(MODEL_ROOT_CAUSE = ROOT_CAUSE, 1, 0)) AS ROOT_CAUSE_AGREEMENT,
       AVG(IFF(MODEL_PRIORITY = PRIORITY, 1, 0))     AS PRIORITY_AGREEMENT
FROM V_CASES WHERE CASE_STATUS = 'REVIEWED' GROUP BY 1, 2, 3;
