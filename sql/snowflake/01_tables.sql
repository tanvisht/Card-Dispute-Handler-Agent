USE SCHEMA DISPUTE_TRIAGE.CORE;

-- Landing table for write_pandas; truncated after each MERGE.
CREATE TABLE IF NOT EXISTS STG_COMPLAINTS (
  COMPLAINT_ID STRING, DATE_RECEIVED DATE, PRODUCT STRING, SUB_PRODUCT STRING, ISSUE STRING,
  SUB_ISSUE STRING, NARRATIVE STRING, COMPANY STRING, STATE STRING, SUBMITTED_VIA STRING,
  COMPANY_RESPONSE STRING, TIMELY STRING, DATE_SENT_TO_COMPANY DATE);

CREATE TABLE IF NOT EXISTS RAW_COMPLAINTS (
  COMPLAINT_ID STRING NOT NULL PRIMARY KEY,
  DATE_RECEIVED DATE, PRODUCT STRING, SUB_PRODUCT STRING, ISSUE STRING, SUB_ISSUE STRING,
  NARRATIVE STRING, COMPANY STRING, STATE STRING, SUBMITTED_VIA STRING,
  COMPANY_RESPONSE STRING, TIMELY STRING, DATE_SENT_TO_COMPANY DATE,
  LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());

-- Append-only: every model/prompt version run is kept for audit + A/B comparison.
CREATE TABLE IF NOT EXISTS CLASSIFICATIONS (
  COMPLAINT_ID STRING NOT NULL, ROOT_CAUSE STRING, VISA_REASON_CODE STRING,
  MASTERCARD_REASON_CODE STRING, REASON_CODE_LABEL STRING, PRIORITY STRING,
  IS_FRAUD BOOLEAN, CONFIDENCE FLOAT, RATIONALE STRING, EVIDENCE_QUOTE STRING,
  NEEDS_HUMAN_REVIEW BOOLEAN, REVIEW_REASONS STRING, CLASSIFIER STRING,
  PROMPT_VERSION STRING, CLASSIFIED_AT TIMESTAMP_TZ)
  CLUSTER BY (TO_DATE(CLASSIFIED_AT));

CREATE TABLE IF NOT EXISTS REVIEW_DECISIONS (
  COMPLAINT_ID STRING NOT NULL, REVIEWER STRING, ROOT_CAUSE STRING, PRIORITY STRING,
  NOTES STRING, REVIEWED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());
